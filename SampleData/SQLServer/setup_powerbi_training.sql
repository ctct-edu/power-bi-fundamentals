IF DB_ID(N'PowerBITraining') IS NULL
BEGIN
    CREATE DATABASE PowerBITraining;
END;
GO

USE PowerBITraining;
GO

IF OBJECT_ID(N'dbo.商品マスター', N'U') IS NOT NULL DROP TABLE dbo.商品マスター;
IF OBJECT_ID(N'dbo.店舗マスター', N'U') IS NOT NULL DROP TABLE dbo.店舗マスター;
GO

CREATE TABLE dbo.商品マスター (
    商品ID nvarchar(10) NOT NULL CONSTRAINT PK_商品マスター PRIMARY KEY,
    商品名 nvarchar(100) NOT NULL,
    商品カテゴリ nvarchar(50) NOT NULL,
    標準単価 decimal(12,0) NOT NULL,
    標準原価 decimal(12,0) NOT NULL,
    販売開始日 date NOT NULL
);

CREATE TABLE dbo.店舗マスター (
    店舗ID nvarchar(10) NOT NULL CONSTRAINT PK_店舗マスター PRIMARY KEY,
    店舗名 nvarchar(100) NOT NULL,
    地域 nvarchar(50) NOT NULL,
    都道府県 nvarchar(20) NOT NULL,
    開店日 date NOT NULL
);
GO

